/* =========================================
   CREATE LIST ITEMS
   ========================================= */

function createList(id, items) {

    const list = document.getElementById(id);

    list.innerHTML = "";

    items.forEach(function(item) {

        const li = document.createElement("li");

        li.textContent = item;

        list.appendChild(li);

    });
}


